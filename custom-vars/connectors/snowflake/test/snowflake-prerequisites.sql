-- Privacera PolicySync prerequisites for Snowflake.
-- Run this file in Snowsight as ACCOUNTADMIN.
--
-- This script deliberately does not DROP existing objects and does not contain
-- passwords. Set the service-user password separately as described in README.md.

USE ROLE ACCOUNTADMIN;

CREATE ROLE IF NOT EXISTS "PRIVACERA_POLICYSYNC_ROLE";

GRANT CREATE ROLE ON ACCOUNT TO ROLE "PRIVACERA_POLICYSYNC_ROLE";
GRANT CREATE USER ON ACCOUNT TO ROLE "PRIVACERA_POLICYSYNC_ROLE";
GRANT MANAGE GRANTS ON ACCOUNT TO ROLE "PRIVACERA_POLICYSYNC_ROLE";
GRANT APPLY MASKING POLICY ON ACCOUNT TO ROLE "PRIVACERA_POLICYSYNC_ROLE";

CREATE WAREHOUSE IF NOT EXISTS "PRIVACERA_POLICYSYNC_WH"
  WAREHOUSE_SIZE = 'XSMALL'
  WAREHOUSE_TYPE = 'STANDARD'
  AUTO_SUSPEND = 600
  AUTO_RESUME = TRUE
  MIN_CLUSTER_COUNT = 1
  MAX_CLUSTER_COUNT = 1
  INITIALLY_SUSPENDED = TRUE;

-- Reconcile mutable settings if the warehouse already existed.
ALTER WAREHOUSE "PRIVACERA_POLICYSYNC_WH" SET
  WAREHOUSE_SIZE = 'XSMALL'
  AUTO_SUSPEND = 600
  AUTO_RESUME = TRUE
  MIN_CLUSTER_COUNT = 1
  MAX_CLUSTER_COUNT = 1;

GRANT USAGE ON WAREHOUSE "PRIVACERA_POLICYSYNC_WH"
  TO ROLE "PRIVACERA_POLICYSYNC_ROLE";
GRANT OPERATE ON WAREHOUSE "PRIVACERA_POLICYSYNC_WH"
  TO ROLE "PRIVACERA_POLICYSYNC_ROLE";

-- Allows Privacera to read ACCOUNT_USAGE audit data in the shared SNOWFLAKE DB.
GRANT IMPORTED PRIVILEGES ON DATABASE SNOWFLAKE
  TO ROLE "PRIVACERA_POLICYSYNC_ROLE";

CREATE DATABASE IF NOT EXISTS "PRIVACERA_DB";
GRANT USAGE ON DATABASE "PRIVACERA_DB"
  TO ROLE "PRIVACERA_POLICYSYNC_ROLE";
GRANT USAGE ON SCHEMA "PRIVACERA_DB".PUBLIC
  TO ROLE "PRIVACERA_POLICYSYNC_ROLE";
GRANT CREATE FUNCTION ON SCHEMA "PRIVACERA_DB".PUBLIC
  TO ROLE "PRIVACERA_POLICYSYNC_ROLE";

-- The user is created without a password so no credential enters Git history.
CREATE USER IF NOT EXISTS "PRIVACERA_POLICYSYNC_USER"
  DEFAULT_WAREHOUSE = "PRIVACERA_POLICYSYNC_WH"
  DEFAULT_ROLE = "PRIVACERA_POLICYSYNC_ROLE"
  MUST_CHANGE_PASSWORD = FALSE;

ALTER USER "PRIVACERA_POLICYSYNC_USER" SET
  DEFAULT_WAREHOUSE = "PRIVACERA_POLICYSYNC_WH"
  DEFAULT_ROLE = "PRIVACERA_POLICYSYNC_ROLE"
  MUST_CHANGE_PASSWORD = FALSE;

GRANT ROLE "PRIVACERA_POLICYSYNC_ROLE"
  TO USER "PRIVACERA_POLICYSYNC_USER";

-- Free-trial accounts may reject this statement with error 391811. If that
-- happens, the trial does not support Privacera-managed row access policies.
-- Run it separately so an expected trial limitation cannot stop the setup above.
GRANT APPLY ROW ACCESS POLICY ON ACCOUNT
  TO ROLE "PRIVACERA_POLICYSYNC_ROLE";
